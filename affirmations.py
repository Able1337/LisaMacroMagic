class PhraseSchedule:
    def __init__(self,rng=None):
        self.remaining=[phrase for phrase in PHRASES if phrase!=FOX_HINT]
        (rng or random.SystemRandom()).shuffle(self.remaining)
        self.slot=None
        self.current=''
        self.last_regular=''

    def update(self,now):
        slot=(now.date(),now.hour,now.minute//10)
        if slot==self.slot: return self.current
        self.slot=slot
        if now.hour%6==0 and now.minute<10:
            self.current=FOX_HINT
        else:
            if self.remaining: self.last_regular=self.remaining.pop()
            self.current=self.last_regular
        return self.current


class AffirmationCard(QFrame):
    def __init__(self,parent=None):
        super().__init__(parent)
        self.setObjectName('affirmationCard')
        self.setMinimumWidth(260); self.setMaximumWidth(390)
        self.setToolTip('Новая фраза каждые 10 минут по часам Windows ♡')
        layout=QVBoxLayout(self); layout.setContentsMargins(14,9,14,9); layout.setSpacing(3)
        caption=QLabel('A LITTLE REMINDER ♡'); caption.setObjectName('affirmationCaption'); layout.addWidget(caption)
        self.message=QLabel(); self.message.setObjectName('affirmationText'); self.message.setWordWrap(True)
        self.message.setMinimumHeight(36); layout.addWidget(self.message)
        self.schedule=PhraseSchedule(); self.refresh()
        self.timer=QTimer(self); self.timer.setInterval(1000); self.timer.timeout.connect(self.refresh); self.timer.start()

    def refresh(self):
        text=self.schedule.update(datetime.now())
        if self.message.text()!=text: self.message.setText(text)
